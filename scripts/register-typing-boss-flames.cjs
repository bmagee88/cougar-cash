// Recover whole silhouettes from the master, retaining registration and adding atlas gutters.
const fs=require('node:fs/promises'),path=require('node:path'),sharp=require('sharp');
const {components}=require('./sprite-components.cjs');
const root=path.resolve(__dirname,'../public/assets/typing-boss/dragons');
(async()=>{
  const manifest=JSON.parse(await fs.readFile(path.join(root,'flame-20-manifest.json'),'utf8'));
  const feet=JSON.parse(await fs.readFile(path.join(root,'footing-manifest.json'),'utf8')),registration={};
  for(const [id,name]of Object.entries({infernalDragon:'ancient-red-dragon',cindermaw:'cindermaw',emberWhelp:'ember-whelp'})){
    const {data,info}=await sharp(path.join(root,`${name}-flame-20.png`)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const parts=components(data,info.width,info.height,128,true),bodies=parts.filter(p=>p.size>10000).sort((a,b)=>a.cy-b.cy),ordered=[];
    if(bodies.length!==20)throw Error(`${id}: expected 20 complete silhouettes`);
    for(let row=0;row<4;row++)ordered.push(...bodies.slice(row*5,row*5+5).sort((a,b)=>a.cx-b.cx));
    const owners=new Int16Array(info.width*info.height).fill(-1);
    for(const p of parts){
      let owner=ordered.indexOf(p);
      if(owner<0){let best=Infinity;ordered.forEach((b,i)=>{const dx=Math.max(b.left-p.right,p.left-b.right,0),dy=Math.max(b.top-p.bottom,p.top-b.bottom,0),score=dx*dx+dy*dy+((p.cx-b.cx)**2+(p.cy-b.cy)**2)*.025;if(score<best){best=score;owner=i;}});if(best>5000)continue;}
      for(const index of p.indices)for(let dy=-2;dy<=2;dy++)for(let dx=-2;dx<=2;dx++){
        const x=index%info.width+dx,y=Math.floor(index/info.width)+dy;if(x>=0&&y>=0&&x<info.width&&y<info.height)owners[y*info.width+x]=owner;
      }
    }
    const tiles=[];
    for(let i=0;i<20;i++){
      const col=i%5,row=Math.floor(i/5),left=Math.round(col*info.width/5),top=Math.round(row*info.height/4),w=Math.round((col+1)*info.width/5)-left,h=Math.round((row+1)*info.height/4)-top,pixels=Buffer.alloc(320*320*4);
      for(let y=0;y<320;y++)for(let x=0;x<320;x++){
        const sx=Math.floor(left+(x-32+.5)*w/256),sy=Math.floor(top+(y-32+.5)*h/256);
        if(sx<0||sy<0||sx>=info.width||sy>=info.height)continue;
        const source=sy*info.width+sx;if(owners[source]===i)data.copy(pixels,(y*320+x)*4,source*4,source*4+4);
      }
      tiles.push({input:await sharp(pixels,{raw:{width:320,height:320,channels:4}}).png().toBuffer(),left:col*320,top:row*320});
    }
    await sharp({create:{width:1600,height:1280,channels:4,background:'#00000000'}}).composite(tiles).webp({lossless:true}).toFile(path.join(root,`${name}-flame-20-v2.webp`));
    const {frames,scaleX,scaleY}=manifest.dragons[id],reference=feet[id].reference;
    registration[id]={cell:320,camera:feet[id].camera,frames:frames.map(foot=>({scaleX,scaleY,x:reference.right-scaleX*(foot.right+32),y:reference.ground-scaleY*(foot.ground+32)}))};
  }
  await fs.writeFile(path.resolve(root,'../../../../src/TypingBoss/dragonFlameRegistration.ts'),'// Generated by scripts/register-typing-boss-flames.cjs. Whole silhouettes with 32px gutters.\nconst registration = '+JSON.stringify(registration,null,2)+';\nexport default registration;\n');
  console.log('Recovered 60 complete flame frames with protected gutters.');
})().catch(e=>{console.error(e);process.exitCode=1;});
