const fs=require("node:fs/promises"),path=require("node:path"),sharp=require("sharp");
const root=path.resolve(__dirname,"../public/assets/typing-boss/characters");
const classes=["paladin","cleric","barbarian","rogue","necromancer","monk"];
const labels=["idle / receiving buff","weapon / power","support cast","receiving healing","dodge","hit / block / receiving shield","being revived","death / knocked out"];
(async()=>{
  const registration={},report=[];
  for(const id of classes){
    const candidates=[`${id}-combat-v3.webp`,`${id}-combat-v2.webp`,`${id}-combat.webp`];
    let filename;
    for(const candidate of candidates)try{await fs.access(path.join(root,candidate));filename=candidate;break;}catch{}
    const {data,info}=await sharp(path.join(root,filename)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const width=info.width/6,height=info.height/8;
    if(!Number.isInteger(width)||!Number.isInteger(height)||height<96)throw new Error(`Invalid atlas grid: ${id}`);
    const verticalPadding=(height-96)/2;
    const rows=[],clips=[];
    for(let row=0;row<8;row++){
      const anchors=[],frames=[];
      for(let frame=0;frame<6;frame++){
        let sum=0,count=0,edgePixels=0,opaque=0;
        for(let y=0;y<height;y++)for(let x=0;x<width;x++){
          const alpha=data[((row*height+y)*info.width+frame*width+x)*4+3];
          if(alpha>=230){opaque++;if(y>=72+verticalPadding&&y<91+verticalPadding){sum+=x;count++;}}
          if(alpha>=128&&(x===0||x===width-1||y===0||y===height-1))edgePixels++;
        }
        if(!count||opaque<120)throw new Error(`Missing character: ${id} ${row} ${frame}`);
        anchors.push(Number((sum/count).toFixed(4)));
        frames.push({frame:frame+1,opaquePixels:opaque,edgePixels});
      }
      rows.push(anchors);
      clips.push({row,action:labels[row],rawHorizontalDrift:Number((Math.max(...anchors)-Math.min(...anchors)).toFixed(3)),frames});
    }
    registration[id]={filename,cellWidth:width,cellHeight:height,repairedWeapon:filename!==`${id}-combat.webp`,anchors:rows};
    report.push({id,filename,clips});
  }
  await fs.writeFile(path.resolve(root,"../../../../src/TypingBoss/characterRegistration.ts"),"// Generated by scripts/audit-typing-boss-sprites.cjs; re-run after replacing artwork.\nconst registration = "+JSON.stringify(registration,null,2)+";\nexport default registration;\n");
  await fs.writeFile(path.join(root,"sprite-audit.json"),JSON.stringify(report,null,2)+"\n");
  const edges=report.flatMap(r=>r.clips.flatMap(c=>c.frames.filter(f=>f.edgePixels).map(f=>({classId:r.id,action:c.action,frame:f.frame,edgePixels:f.edgePixels}))));
  console.log(JSON.stringify({classes:6,clips:48,frames:288,borderIssues:edges}));
  if(process.argv.includes("--check")&&edges.length)process.exitCode=1;
})().catch(error=>{console.error(error);process.exitCode=1;});
