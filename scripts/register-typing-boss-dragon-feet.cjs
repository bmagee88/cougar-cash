// Read-only sprite analysis. Artwork is unchanged; CSS uses the resulting registration.
const fs=require("node:fs/promises"),path=require("node:path"),sharp=require("sharp");
const root=path.resolve(__dirname,"../public/assets/typing-boss/dragons"),CELL=256;
const ids={infernalDragon:"ancient-red-dragon",cindermaw:"cindermaw",emberWhelp:"ember-whelp"};
const quantile=(values,p)=>values.slice().sort((a,b)=>a-b)[Math.floor(values.length*p)];
function contacts(data,stride,row,frame,hint){
  const points=[],hist=Array(CELL).fill(0);
  for(let y=188;y<235;y++)for(let x=24;x<238;x++){
    const i=((row*CELL+y)*stride+frame*CELL+x)*4,r=data[i],g=data[i+1],b=data[i+2];
    // Bone/ivory claws, excluding red scales, orange flame and the upper body.
    if(data[i+3]>180&&r>120&&g>105&&b>70&&g/r>.65&&b/r>.42){points.push([x,y]);hist[y]++;}
  }
  let peak=188,best=0;
  for(let y=hint===undefined?190:hint-6;y<=(hint===undefined?228:hint);y++){
    const score=hist.slice(y,y+6).reduce((n,v)=>n+v,0);
    if(score>best){best=score;peak=y;}
  }
  const feet=points.filter(p=>p[1]>=peak-2&&p[1]<=peak+7);
  if(feet.length<25)throw new Error(`Cannot locate dragon footing: ${row} ${frame}`);
  return {left:quantile(feet.map(p=>p[0]),.1),right:quantile(feet.map(p=>p[0]),.9),ground:quantile(feet.map(p=>p[1]),.9),samples:feet.length};
}
(async()=>{
  const registration={};
  for(const [bossId,id]of Object.entries(ids)){
    const {data,info}=await sharp(path.join(root,`${id}-attacks-v2.webp`)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    if(info.width!==CELL*6||info.height!==CELL*4)throw new Error(`Unexpected dragon atlas geometry: ${id}`);
    const rows=[];
    for(let row=0;row<4;row++){
      const frames=[];let hint;
      for(let frame=0;frame<6;frame++){const foot=contacts(data,info.width,row,frame,hint);if(hint===undefined)hint=foot.ground;frames.push({...foot});}
      rows.push(frames);
    }
    const reference=rows[0][0],span=reference.right-reference.left;
    for(let row=0;row<4;row++)for(let f=0;f<6;f++){
      const foot=rows[row][f],occluded=id==="ancient-red-dragon"&&row===2&&(f===3||f===4);
      // A sweeping tail hides the rear contact in these two poses. Register the
      // visible forefoot; interpolate width from neighboring unobscured poses.
      const a=occluded ? (span/(rows[row][2].right-rows[row][2].left))*(1-(f-2)/3)+(span/(rows[row][5].right-rows[row][5].left))*((f-2)/3) : span/(foot.right-foot.left);
      foot.scaleX=Number(a.toFixed(7));foot.x=Number((reference.left-a*foot.left).toFixed(7));foot.y=reference.ground-foot.ground;foot.occluded=occluded;
      if(a<.75||a>1.25)throw new Error(`Suspicious foot registration: ${id} ${row} ${f}`);
    }
    let x0=Infinity,y0=Infinity,x1=-Infinity,y1=-Infinity;
    for(let row=0;row<4;row++)for(let f=0;f<6;f++){
      const foot=rows[row][f];let b={left:Infinity,top:Infinity,right:-Infinity,bottom:-Infinity};
      for(let y=0;y<CELL;y++)for(let x=0;x<CELL;x++)if(data[((row*CELL+y)*info.width+f*CELL+x)*4+3]){
        const tx=x*foot.scaleX+foot.x,ty=y+foot.y;
        b.left=Math.min(b.left,tx);b.right=Math.max(b.right,tx);b.top=Math.min(b.top,ty);b.bottom=Math.max(b.bottom,ty);
      }
      foot.bounds=b;x0=Math.min(x0,b.left);x1=Math.max(x1,b.right);y0=Math.min(y0,b.top);y1=Math.max(y1,b.bottom);
      if(Math.abs(foot.left*foot.scaleX+foot.x-reference.left)>.0001||Math.abs(foot.ground+foot.y-reference.ground)>.0001||(!foot.occluded&&Math.abs(foot.right*foot.scaleX+foot.x-reference.right)>.0001))throw new Error(`Foot registration drift: ${id}`);
    }
    // A single camera for the entire dragon, with space above/below the fixed ground.
    const size=Math.ceil(Math.max(x1-x0+24,(reference.ground-y0+12)/.86,(y1-reference.ground+12)/.14));
    const left=(x0+x1-size)/2,top=reference.ground-size*.86;
    for(const row of rows)for(const foot of row){
      if(foot.bounds.left<left+11.9||foot.bounds.right>left+size-11.9||foot.bounds.top<top+11.9||foot.bounds.bottom>top+size-11.9)throw new Error(`Dragon camera crops artwork: ${id}`);
      if(.04+(foot.bounds.top-top)/size<0||.04+(foot.bounds.bottom-top)/size>1)throw new Error(`Dragon exceeds the layout area: ${id}`);
    }
    registration[bossId]={cell:CELL,camera:{size,left,top},reference:{left:reference.left,right:reference.right,ground:reference.ground},rows};
  }
  const runtime=Object.fromEntries(Object.entries(registration).map(([id,r])=>[id,{cell:r.cell,camera:r.camera,rows:r.rows.map(row=>row.map(({scaleX,x,y})=>({scaleX,x,y})))}]));
  await fs.writeFile(path.resolve(root,"../../../../src/TypingBoss/dragonRegistration.ts"),"// Generated by scripts/register-typing-boss-dragon-feet.cjs.\n// Pixel measurements and validation details remain in dragons/footing-manifest.json.\nconst registration = "+JSON.stringify(runtime,null,2)+";\nexport default registration;\n");
  await fs.writeFile(path.join(root,"footing-manifest.json"),JSON.stringify(registration,null,2)+"\n");
  console.log(JSON.stringify({frames:72,footing:"registered",cameraGutter:12,cameras:Object.fromEntries(Object.entries(registration).map(([id,r])=>[id,r.camera]))}));
})().catch(error=>{console.error(error);process.exitCode=1;});
