// Mechanical atlas packing and foot registration only; generated artwork stays untouched.
const fs = require('node:fs/promises'), path = require('node:path'), sharp = require('sharp');
const { DRAGON_FLAME } = require('../src/TypingBoss/dragonHurtRules');
const root = path.resolve(__dirname, '../public/assets/typing-boss/dragons');
const ids = { infernalDragon:'ancient-red-dragon', cindermaw:'cindermaw', emberWhelp:'ember-whelp' };
const quantile = (values, fraction) => values.slice().sort((a,b)=>a-b)[Math.floor(values.length*fraction)];
function measure(pixels) {
  const claws=[], histogram=Array(256).fill(0);
  let top=256,leftBound=256,rightBound=0,solid=0,clear=0;
  for(let y=0;y<256;y++) for(let x=0;x<256;x++) {
    const i=(y*256+x)*4,[r,g,b,a]=pixels.subarray(i,i+4);
    if(a<10) clear++;
    if(a>180) {solid++;top=Math.min(top,y);leftBound=Math.min(leftBound,x);rightBound=Math.max(rightBound,x);}
    if(y>=145 && a>180 && r>120 && g>105 && b>70 && g/r>.65 && b/r>.42) {claws.push([x,y]);histogram[y]++;}
  }
  if(solid<1000 || clear<3000) throw Error('Flame frame is empty or lacks transparency');
  let peak=150,best=0;
  for(let y=150;y<251;y++) {const score=histogram.slice(y,y+6).reduce((a,b)=>a+b,0);if(score>=best){best=score;peak=y;}}
  const feet=claws.filter(([,y])=>y>=peak-2 && y<=peak+7);
  if(feet.length<12) throw Error('Could not register flame-frame feet');
  return {right:quantile(feet.map(([x])=>x),.9),ground:quantile(feet.map(([,y])=>y),.9),top,leftBound,rightBound,solid,clear};
}
(async()=>{
  const baseline=JSON.parse(await fs.readFile(path.join(root,'footing-manifest.json'),'utf8')),runtime={},report={};
  for(const [boss,id] of Object.entries(ids)) {
    const bytes=await fs.readFile(path.join(root,`${id}-flame-20.png`)),meta=await sharp(bytes).metadata(),tiles=[],measurements=[];
    if(!meta.hasAlpha || Math.abs(meta.width/meta.height-1.25)>.03) throw Error(`Expected transparent 5×4 master: ${id}`);
    for(let index=0;index<20;index++) {
      const col=index%5,row=Math.floor(index/5),left=Math.round(col*meta.width/5),top=Math.round(row*meta.height/4);
      const width=Math.round((col+1)*meta.width/5)-left,height=Math.round((row+1)*meta.height/4)-top;
      const tile=await sharp(bytes).extract({left,top,width,height}).resize(256,256,{kernel:'nearest'}).ensureAlpha().png().toBuffer();
      tiles.push(tile);
      try { measurements.push(measure(await sharp(tile).raw().toBuffer())); }
      catch(error) { throw Error(`${id} frame ${index+1}: ${error.message}`); }
    }
    const original=baseline[boss],reference=original.reference,neutral=measurements[19],bounds=original.rows[0][0].bounds;
    const scaleX=(bounds.right-bounds.left)/(neutral.rightBound-neutral.leftBound);
    const scaleY=Math.min((reference.ground-bounds.top)/(neutral.ground-neutral.top),
      (reference.ground-original.camera.top-10)/Math.max(...measurements.map(frame=>frame.ground-frame.top)));
    const frames=measurements.map(foot=>({scaleX,scaleY,x:reference.right-scaleX*foot.right,y:reference.ground-scaleY*foot.ground}));
    await sharp({create:{width:1280,height:1024,channels:4,background:'#00000000'}})
      .composite(tiles.map((input,index)=>({input,left:index%5*256,top:Math.floor(index/5)*256})))
      .webp({lossless:true,effort:6}).toFile(path.join(root,`${id}-flame-20.webp`));
    runtime[boss]={cell:256,camera:original.camera,frames};
    report[boss]={source:{width:meta.width,height:meta.height},frames:measurements,scaleX,scaleY,runtimeBytes:(await fs.stat(path.join(root,`${id}-flame-20.webp`))).size};
  }
  await fs.writeFile(path.resolve(root,'../../../../src/TypingBoss/dragonFlameRegistration.ts'),
    '// Generated by scripts/prepare-typing-boss-dragon-flame.cjs. Artwork is unchanged.\nconst registration = '+JSON.stringify(runtime,null,2)+';\nexport default registration;\n');
  await fs.writeFile(path.join(root,'flame-20-manifest.json'),JSON.stringify({layout:{...DRAGON_FLAME,cell:256},dragons:report},null,2)+'\n');
  console.log('Packed and registered 20 flame-breath frames for all three dragons.');
})().catch(error=>{console.error(error);process.exitCode=1;});
