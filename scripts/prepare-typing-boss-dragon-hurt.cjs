// Mechanical cell packing and read-only foot registration. PNG masters stay untouched.
const fs = require('node:fs/promises'), path = require('node:path'), sharp = require('sharp');
const { DRAGON_HURT } = require('../src/TypingBoss/dragonHurtRules');
const root = path.resolve(__dirname, '../public/assets/typing-boss/dragons');
const ids = { infernalDragon: 'ancient-red-dragon', cindermaw: 'cindermaw', emberWhelp: 'ember-whelp' };
const quantile = (values, fraction) => values.slice().sort((a,b) => a-b)[Math.floor(values.length * fraction)];

function measure(pixels) {
  const claws = [], histogram = Array(256).fill(0); let top = 256, bottom = 0, leftBound = 256, rightBound = 0, clear = 0, solid = 0;
  for (let y=0;y<256;y++) for (let x=0;x<256;x++) {
    const i=(y*256+x)*4, [r,g,b,a]=pixels.subarray(i,i+4);
    if(a<10) clear++;
    if(a>180) { solid++; top=Math.min(top,y); bottom=Math.max(bottom,y); leftBound=Math.min(leftBound,x); rightBound=Math.max(rightBound,x); }
    if(y>=165 && a>180 && r>120 && g>105 && b>70 && g/r>.65 && b/r>.42) { claws.push([x,y]); histogram[y]++; }
  }
  if(solid<1000 || clear<3000) throw Error('Hurt frame is empty or lacks transparency');
  let peak=180, best=0;
  for(let y=180;y<251;y++) { const score=histogram.slice(y,y+6).reduce((a,b)=>a+b,0); if(score>=best){best=score;peak=y;} }
  const feet=claws.filter(([,y])=>y>=peak-2 && y<=peak+7);
  if(feet.length<12) throw Error('Could not register hurt-frame feet');
  return { left:quantile(feet.map(([x])=>x),.1), right:quantile(feet.map(([x])=>x),.9), ground:quantile(feet.map(([,y])=>y),.9), top, bottom, leftBound, rightBound, solid, clear };
}

(async()=>{
  const baseline=JSON.parse(await fs.readFile(path.join(root,'footing-manifest.json'),'utf8'));
  const runtime={}, report={};
  for(const [boss,id] of Object.entries(ids)) {
    const source=path.join(root,`${id}-hurt.png`), sourceBytes=await fs.readFile(source), meta=await sharp(sourceBytes).metadata();
    if(!meta.hasAlpha || Math.abs(meta.width/meta.height-1.25)>.03) throw Error(`Expected transparent 5×4 hurt master: ${id}`);
    const tiles=[], measurements=[];
    for(let index=0;index<20;index++) {
      const column=index%5,row=Math.floor(index/5),left=Math.round(column*meta.width/5),top=Math.round(row*meta.height/4);
      const width=Math.round((column+1)*meta.width/5)-left,height=Math.round((row+1)*meta.height/4)-top;
      const tile=await sharp(sourceBytes).extract({left,top,width,height}).resize(256,256,{kernel:'nearest'}).ensureAlpha().png().toBuffer();
      tiles.push(tile); measurements.push(measure(await sharp(tile).raw().toBuffer()));
    }
    const original=baseline[boss], reference=original.reference, neutral=measurements[19];
    // A crouch can hide the forefoot. Keep one scale for the entire sequence
    // and register the visible hind contact, rather than stretching the torso
    // when a smaller set of claws is exposed in a severe reaction.
    const originalBounds=original.rows[0][0].bounds;
    const scaleX=(originalBounds.right-originalBounds.left)/(neutral.rightBound-neutral.leftBound);
    if(scaleX<.45 || scaleX>1.8) throw Error(`Implausible hurt registration: ${id} (${scaleX})`);
    const maximumHeadroom=Math.max(...measurements.map(frame=>frame.ground-frame.top));
    const scaleY=Math.min((reference.ground-original.rows[0][0].bounds.top)/(neutral.ground-neutral.top),
      (reference.ground-original.camera.top-10)/maximumHeadroom);
    const composites=[], tiers={};
    for(const [tier,config] of Object.entries(DRAGON_HURT)) {
      const row=Object.keys(DRAGON_HURT).indexOf(tier), frames=[];
      for(let frame=0;frame<config.frames;frame++) {
        const sourceIndex=config.start+frame, foot=measurements[sourceIndex];
        frames.push({ scaleX,scaleY,x:reference.right-scaleX*foot.right,y:reference.ground-scaleY*foot.ground });
        composites.push({input:tiles[sourceIndex],left:frame*256,top:row*256});
      }
      tiers[tier]=frames;
    }
    await sharp({create:{width:2560,height:768,channels:4,background:'#00000000'}}).composite(composites)
      .webp({lossless:true,effort:6}).toFile(path.join(root,`${id}-hurt.webp`));
    runtime[boss]={cell:256,camera:original.camera,tiers};
    report[boss]={source:{width:meta.width,height:meta.height},frames:measurements,scaleY,runtimeBytes:(await fs.stat(path.join(root,`${id}-hurt.webp`))).size};
  }
  await fs.writeFile(path.resolve(root,'../../../../src/TypingBoss/dragonHurtRegistration.ts'),
    '// Generated by scripts/prepare-typing-boss-dragon-hurt.cjs. Artwork is unchanged.\nconst registration = '+JSON.stringify(runtime,null,2)+';\nexport default registration;\n');
  await fs.writeFile(path.join(root,'hurt-manifest.json'),JSON.stringify({layout:{columns:10,rows:3,cell:256,tiers:DRAGON_HURT},dragons:report},null,2)+'\n');
  console.log('Packed 3/6/10-frame hurt tiers for all three dragons; feet registered to their existing attack camera.');
})().catch(error=>{console.error(error);process.exitCode=1;});
