export function getConceptsForTopic(topic: TopicFilter): VocabularyConcept[] {
  if (topic === "mixed") {
    return VOCABULARY;
  }

  return VOCABULARY.filter((concept) => concept.topic === topic);
}

export function findConceptById(id: string): VocabularyConcept | undefined {
  return VOCABULARY.find((concept) => concept.id === id);
}

