test('real game hook saves exactly one line loss after a snap, keeps other spools, and can cast again',()=>{
  const save=emptySave();save.settings.fishingMode='fish-fight';save.lineGear={...readLineGear(),equipped:6};localStorage.setItem(SAVE_KEY,JSON.stringify(save));
  const random=jest.spyOn(Math,'random').mockReturnValue(.99);
  const hook=renderHook(()=>useFishingGame(s=>({season:'summer',period:'morning',moonPhase:'full',fightOptions:{testLb:6,spoolM:s.lineGear!.spools[6],wordCheckpoint:false}})));
  act(()=>hook.result.current.castLine());act(()=>jest.advanceTimersByTime(900));
  const retrieve=hook.result.current.game as Extract<GameState,{phase:'retrieving'}>;
  const poem=retrieve.retrieve.typing.phrase;
  act(()=>{for(const char of poem.slice(0,15))hook.result.current.key(char);});
  random.mockReturnValue(0);
  act(()=>hook.result.current.key(poem[15]));
  expect(hook.result.current.game.phase).toBe('typing');act(()=>hook.result.current.armChallenge());
  for(let i=0;i<20;i++)act(()=>jest.advanceTimersByTime(100));
  const fighting=hook.result.current.game as Extract<GameState,{phase:'typing'}>;
  expect(fighting.fight!.jolt).toBeDefined();
  act(()=>{for(const char of poem.slice(16,22))hook.result.current.key(char);});
  expect(hook.result.current.game).toMatchObject({phase:'result',outcome:'escaped',reason:'line-snapped'});
  expect(hook.result.current.save.lineGear!.spools[6]).toBe(270);
  expect(hook.result.current.save.lineGear!.spools[10]).toBe(300);
  act(()=>jest.advanceTimersByTime(1000));expect(hook.result.current.save.lineGear!.spools[6]).toBe(270);
  expect(JSON.parse(localStorage.getItem(SAVE_KEY)!).lineGear.spools[6]).toBe(270);
  act(()=>hook.result.current.again());act(()=>hook.result.current.castLine());expect(hook.result.current.game.phase).toBe('casting');
  hook.unmount();expect(jest.getTimerCount()).toBe(0);
});
